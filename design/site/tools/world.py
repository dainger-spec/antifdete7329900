# The dotted planet of the home page: points spread evenly over a sphere (a Fibonacci lattice), kept where
# there is land, written to prototype/assets/world.js as 16-bit latitude/longitude pairs in base64.
#
#   python3 -I design/site/tools/world.py <ne_110m_land.geojson>
#
# Land: Natural Earth 1:110m "Land" (public domain, naturalearthdata.com; the file is also at
# github.com/nvkelso/natural-earth-vector, geojson/ne_110m_land.geojson). The site loads nothing from a
# network: only the derived points ship, in world.js.
import base64, json, math, os, struct, sys

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = 26000  # points on the whole sphere; about 29 % fall on land

def rings(geometry):
    if geometry['type'] == 'Polygon':
        yield geometry['coordinates']
    elif geometry['type'] == 'MultiPolygon':
        for poly in geometry['coordinates']:
            yield poly

def inside(lon, lat, ring):
    # Ray casting in lon/lat; fine at this scale away from the poles' edges.
    hit = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][0], ring[i][1]
        xj, yj = ring[j][0], ring[j][1]
        if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi + 1e-12) + xi:
            hit = not hit
        j = i
    return hit

def main(path):
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    polys = []
    for feat in data['features']:
        for poly in rings(feat['geometry']):
            outer = poly[0]
            xs = [p[0] for p in outer]; ys = [p[1] for p in outer]
            polys.append((min(xs), max(xs), min(ys), max(ys), poly))
    pts = []
    golden = math.pi * (3 - math.sqrt(5))
    for k in range(N):
        y = 1 - 2 * (k + 0.5) / N
        r = math.sqrt(1 - y * y)
        theta = golden * k
        lat = math.degrees(math.asin(y))
        lon = math.degrees(math.atan2(r * math.sin(theta), r * math.cos(theta)))
        if lat < -60:  # leave Antarctica out: it reads as noise at the bottom of the disc
            continue
        for (x0, x1, y0, y1, poly) in polys:
            if not (x0 <= lon <= x1 and y0 <= lat <= y1):
                continue
            if inside(lon, lat, poly[0]) and not any(inside(lon, lat, hole) for hole in poly[1:]):
                pts.append((lat, lon))
                break
    blob = b''.join(struct.pack('<hh', round(lat * 100), round(lon * 100)) for lat, lon in pts)
    out = os.path.join(SITE, 'prototype', 'assets', 'world.js')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('// Land points of the home page planet: generated by tools/world.py from Natural Earth 1:110m land\n'
                '// (public domain). Pairs of little-endian int16: latitude × 100, longitude × 100.\n'
                f'window.LUMEN_WORLD = "{base64.b64encode(blob).decode()}";\n')
    print(f'WROTE prototype/assets/world.js: {len(pts)} land points, {len(blob)} bytes')

if __name__ == '__main__':
    main(sys.argv[1])
