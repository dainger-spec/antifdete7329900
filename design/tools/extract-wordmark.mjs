// Reads LumenWordmarkShape's outlines straight from LumenMark.swift and writes them as SVG path data,
// so the prototypes draw the real wordmark and not a font look-alike.
// Run: node design/tools/extract-wordmark.mjs  →  design/prototypes/kit/wordmark.js
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const swift = readFileSync(join(root, 'Sources/PrivacyBrowser/UI/LumenMark.swift'), 'utf8');

function outlines(name) {
  const start = swift.indexOf(`static func ${name}(_ p: inout Path`);
  if (start < 0) throw new Error(`no outlines for ${name}`);
  const body = swift.slice(start, swift.indexOf('\n        }', start));
  const num = '(-?[0-9.]+)';
  const pt = `pt\\(${num}, ${num}\\)`;
  let d = '';
  for (const line of body.split('\n')) {
    let m;
    if ((m = line.match(new RegExp(`p\\.move\\(to: ${pt}\\)`)))) d += `M${m[1]} ${m[2]}`;
    else if ((m = line.match(new RegExp(`p\\.addLine\\(to: ${pt}\\)`)))) d += `L${m[1]} ${m[2]}`;
    else if ((m = line.match(new RegExp(`p\\.addCurve\\(to: ${pt}, control1: ${pt}, control2: ${pt}\\)`))))
      d += `C${m[3]} ${m[4]} ${m[5]} ${m[6]} ${m[1]} ${m[2]}`;
    else if (line.includes('p.closeSubpath()')) d += 'Z';
  }
  return d;
}

const regular = outlines('regular');
const small = outlines('small');
// A classic script (not a module): the prototypes are opened from file://, where module imports are blocked.
const out = `// Generated by design/tools/extract-wordmark.mjs from LumenMark.swift (LumenWordmarkShape.Outlines).
// Do not edit by hand.
(function (L) {
  L.WORDMARK = {
    regular: { width: 406, height: 102, d: ${JSON.stringify(regular)} },
    small: { width: 414, height: 102, d: ${JSON.stringify(small)} },
  };
})(globalThis.Lumen = globalThis.Lumen || {});
`;
writeFileSync(join(root, 'design/prototypes/kit/wordmark.js'), out);
console.log('regular', regular.length, 'small', small.length);
