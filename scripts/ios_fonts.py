#!/usr/bin/env python3
"""Writes Sources/BrowserCore/Profiles/IOSFonts.swift from Apple's list of system fonts.

    python3 scripts/ios_fonts.py                 # reads https://developer.apple.com/fonts/system-fonts/
    python3 scripts/ios_fonts.py --html page.html  # a saved copy of that page

The page lists every font face Apple ships, by full name, with what each platform has of it:
"system font" (preinstalled), "document support" or "downloadable" ("Additional fonts are
available for download on each platform or through document-based apps"). The faces a Mac has
(a system font, or one for documents, which macOS's WebKit finds too: CI run 228) and iOS and
iPadOS do not preinstall are the ones Safari on an iPhone or iPad lacks: Monaco, Comic Sans MS,
Tahoma, Arial Unicode MS, Lucida Grande, Times, Courier, … An iPhone or iPad profile hides their
families from its pages (DeviceFontRestriction). A face the page marks downloadable on both
platforms is left alone: the systems' CJK fonts (PingFang) are listed so and are on both.
"""
import argparse
import datetime
import html
import os
import re
import sys
import urllib.request

URL = "https://developer.apple.com/fonts/system-fonts/"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Sources", "BrowserCore", "Profiles", "IOSFonts.swift")


def faces(page):
    """{full name: {"macOS": status, "iOS": status}}, status one of system, document, download, none."""
    out = {}
    for item in page.split('<li class="font-item">')[1:]:
        name = re.search(r'class="filter-font-name">([^<]+)</span>', item)
        if not name:
            continue
        tags = set(re.findall(r'<span class="hidden">([^<]+)</span>', item))

        def status(platform):
            for label, value in (("system font", "system"), ("document support", "document"), ("downloadable", "download")):
                if f"{label} {platform}" in tags:
                    return value
            return "none"
        out[html.unescape(name.group(1)).strip()] = {"macOS": status("macOS"), "iOS": status("iOS")}
    return out


def swift_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--html", help="a saved copy of the page instead of reading it")
    parser.add_argument("--out", default=OUT)
    args = parser.parse_args()
    if args.html:
        with open(args.html, encoding="utf-8") as handle:
            page = handle.read()
    else:
        with urllib.request.urlopen(URL, timeout=60) as response:
            page = response.read().decode("utf-8")
    listed = faces(page)
    mac_only = sorted(name for name, status in listed.items()
                      if status["macOS"] in ("system", "document") and status["iOS"] != "system")
    on_ios = sum(1 for status in listed.values() if status["iOS"] == "system")
    if len(listed) < 1000 or len(mac_only) < 100:
        sys.exit(f"ios_fonts: {len(listed)} faces, {len(mac_only)} only on a Mac: the page's layout changed?")
    today = datetime.date.today().isoformat()
    lines = [
        "// Generated by scripts/ios_fonts.py from https://developer.apple.com/fonts/system-fonts/",
        f"// (read {today}: {len(listed)} faces, {on_ios} preinstalled on iOS, {len(mac_only)} below). Do not edit.",
        "",
        "/// The fonts Safari on an iPhone or iPad lacks, by Apple's list of the fonts each system ships.",
        "public enum IOSFonts {",
        "    /// Faces, by full name, that a Mac has (a system font, or one for documents) and iOS and",
        "    /// iPadOS do not preinstall (they offer them for download or to document-based apps).",
        "    public static let macOnlyFaces: Set<String> = [",
    ]
    lines += [f"        {swift_string(name)}," for name in mac_only]
    lines += ["    ]", "}", ""]
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"ios_fonts: {len(listed)} faces listed, {on_ios} preinstalled on iOS, {len(mac_only)} only on a Mac -> "
          f"{os.path.relpath(args.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
