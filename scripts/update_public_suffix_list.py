#!/usr/bin/env python3
"""Regenerates Sources/BrowserCore/Passwords/PublicSuffixList+Rules.swift from the Public Suffix
List (https://publicsuffix.org/list/public_suffix_list.dat, MPL 2.0).

The password manager groups saved logins by registrable domain (eTLD+1), as Safari does; the
list says where a registrable domain begins (`co.uk`, and private suffixes such as `github.io`
whose subdomains belong to different people). Rules are stored in ASCII (IDNA), as WebKit
reports host names.

    curl -o /tmp/psl/public_suffix_list.dat https://publicsuffix.org/list/public_suffix_list.dat
    python3 -I scripts/update_public_suffix_list.py /tmp/psl/public_suffix_list.dat
"""
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "Sources/BrowserCore/Passwords/PublicSuffixList+Rules.swift"


def ascii_rule(rule: str) -> str:
    prefix = ""
    if rule.startswith("!"):
        prefix, rule = "!", rule[1:]
    labels = []
    for label in rule.split("."):
        if label == "*" or label.isascii():
            labels.append(label.lower())
        else:
            labels.append("xn--" + label.lower().encode("punycode").decode("ascii"))
    return prefix + ".".join(labels)


def main() -> None:
    source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    version = next((line.split(":", 1)[1].strip() for line in source.splitlines() if line.startswith("// VERSION:")), "unknown")
    rules = []
    for line in source.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        rule = ascii_rule(line.split()[0])
        if not all(c.isalnum() or c in "-.*!" for c in rule):
            raise SystemExit(f"unexpected rule {rule!r}")
        rules.append(rule)
    body = "\n".join(rules)
    OUT.write_text(
        "// Generated by scripts/update_public_suffix_list.py; do not edit.\n"
        "// Public Suffix List, https://publicsuffix.org/list/public_suffix_list.dat\n"
        f"// VERSION: {version}\n"
        "// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy\n"
        "// of the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.\n"
        "// Internationalized rules are converted to ASCII (Punycode), as WebKit reports host names.\n\n"
        "extension PublicSuffixList {\n"
        f"    static let version = \"{version}\"\n"
        f"    /// {len(rules)} rules, one per line.\n"
        "    static let rulesText = #\"\"\"\n"
        f"{body}\n"
        "\"\"\"#\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(rules)} rules, version {version})")


if __name__ == "__main__":
    main()
