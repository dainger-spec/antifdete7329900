#!/usr/bin/env python3
"""Builds ios/Lumen/Resources/page-shim.js: the macOS app's own page shim (PrivacyScripts.swift's
shimBody — time zone, geolocation, WebRTC, the native-looking replacements, frames and blob workers)
with ios/shim/fingerprint.js appended and called from its patchWindow.

    python3 ios/scripts/build-shim.py           # writes the file
    python3 ios/scripts/build-shim.py --check   # fails if the file is not what the sources make
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SWIFT = os.path.join(ROOT, "Sources/PrivacyBrowser/Browser/PrivacyScripts.swift")
FINGERPRINT = os.path.join(ROOT, "ios/shim/fingerprint.js")
OUT = os.path.join(ROOT, "ios/Lumen/Resources/page-shim.js")
HOOK = "  if (CONFIG.storageQuota) {"


def build():
    body = open(SWIFT, encoding="utf-8").read().split('static let shimBody = #"""')[1].split('"""#')[0]
    if HOOK not in body:
        sys.exit("PrivacyScripts' patchWindow changed: the fingerprint part cannot hook in")
    body = body.replace(HOOK, "  try { patchFingerprint(w, CONFIG.fingerprint); } catch (e) {}\n" + HOOK, 1)
    head = ("// Generated by ios/scripts/build-shim.py from Sources/PrivacyBrowser/Browser/PrivacyScripts.swift\n"
            "// and ios/shim/fingerprint.js. Do not edit: edit those and run the script.\n"
            "// The app wraps it as PrivacyScripts.source does: (function install(CONFIG) { … })(config);\n")
    return head + body + open(FINGERPRINT, encoding="utf-8").read()


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("page-shim.js is not what its sources make: run python3 ios/scripts/build-shim.py")
        print("page-shim.js matches its sources")
    else:
        open(OUT, "w", encoding="utf-8").write(text)
        print(f"wrote {OUT} ({len(text)} bytes)")
